"""Centralized test-data classification and detection utilities.

Provides consistent, fail-safe identification of test, demo, and synthetic
records across all ingestion pathways (manual creation, CSV import, contact creation,
HubSpot sync, and voice call webhooks).

Safeguard guarantees:
1. Prevents synthetic test artifacts from polluting operational CRM views and analytics.
2. Cannot be bypassed by passing explicit False in CSV rows or API payloads with test domains.
3. Does NOT classify genuine client records based solely on unusual email addresses or names.
"""
from __future__ import annotations

import re
from typing import Optional


# Domains specifically used for test, QA, synthetic, or fixture records
TEST_DOMAINS = {
    "blackmesa.org",
    "testacme.com",
    "agiletesting.local",
    "example.com",
    "example.org",
    "example.net",
}

# Domain suffixes reserved by RFC 2606 / RFC 6761 or internal QA subdomains
TEST_DOMAIN_SUFFIXES = (
    ".blackmesa.org",
    ".testacme.com",
    ".agiletesting.local",
    ".example.com",
    ".example.org",
    ".example.net",
    ".test",
    ".invalid",
    ".localhost",
)

# Ingestion sources indicating synthetic or mocked data
TEST_SOURCES = {
    "mock",
    "synthetic",
    "test",
    "qa",
}

# Name tokens and phrases indicating QA/test records (word-boundary scoped to prevent false positives on genuine names)
TEST_NAME_PATTERNS = re.compile(
    r"\b(test\s+(prospect|lead|user|contact|account|org|company)|"
    r"(prospect|lead|user|contact)\s+test|"
    r"qa\s+(test|lead|contact|user)|"
    r"poplar\s+qa)\b",
    re.IGNORECASE,
)

# Company names indicating test entities
TEST_COMPANY_PATTERNS = re.compile(
    r"\b(black\s*mesa|test\s+company|acme\s+test|qa\s+test)\b",
    re.IGNORECASE,
)

# Email prefix patterns commonly generated by automated test runners
EMAIL_PREFIX_PATTERN = re.compile(
    r"^(?:test\d*|qa\d*|csvtest_[a-f0-9]+|tunnel_test)@",
    re.IGNORECASE,
)


def classify_is_test(
    explicit_is_test: Optional[bool] = None,
    email: Optional[str] = None,
    first_name: Optional[str] = None,
    last_name: Optional[str] = None,
    company_name: Optional[str] = None,
    source: Optional[str] = None,
) -> bool:
    """
    Classify whether a lead or contact record is a test/demo record.

    Classification priority:
    1. If explicit_is_test is True, immediately returns True.
    2. If source is a known synthetic source ('mock', 'synthetic', 'test', 'qa'), returns True.
    3. If email matches a known test domain, test prefix, or RFC 2606 reserved domain, returns True.
    4. If name or company contains distinct test identifiers, returns True.
    5. Otherwise, returns False (genuine production record).

    Safety Note: If explicit_is_test is False (or None) but the email or domain matches
    a confirmed test domain (e.g. '@blackmesa.org' or '@example.com'), this function returns
    True to prevent test data from bypassing classification via unvalidated payloads.
    """
    # 1. Explicit True flag always classifies as test
    if explicit_is_test is True:
        return True

    # 2. Known test ingestion source
    if source and source.strip().lower() in TEST_SOURCES:
        return True

    # 3. Email domain and pattern checks
    if email:
        clean_email = email.strip().lower()
        if "@" in clean_email:
            domain = clean_email.split("@")[1].strip()
            if domain in TEST_DOMAINS or any(domain.endswith(sfx) for sfx in TEST_DOMAIN_SUFFIXES):
                return True
            if EMAIL_PREFIX_PATTERN.match(clean_email):
                return True
            if clean_email.startswith("csvtest_") or ".demo@" in clean_email or "+test@" in clean_email or "+qa@" in clean_email:
                return True

    # 4. Name pattern checks (fail-safe whole-word matching)
    fn = (first_name or "").strip().lower()
    ln = (last_name or "").strip().lower()
    if fn in ("test", "qa", "tester", "demo") or ln in ("test", "qa", "tester", "demo"):
        return True

    full_name = f"{first_name or ''} {last_name or ''}".strip()
    if full_name:
        if full_name.lower() in ("test", "qa", "test prospect", "test contact", "test lead", "test user", "tunnel tester"):
            return True
        if TEST_NAME_PATTERNS.search(full_name):
            return True

    # 5. Company pattern check
    if company_name and TEST_COMPANY_PATTERNS.search(company_name.strip()):
        return True

    return False
