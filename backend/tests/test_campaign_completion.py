        comp_id = comp_resp.json()["id"]

        c_resp = await client.post(
            "/api/v1/contacts",
            json={"first_name": "Maya", "last_name": "Lin", "email": "maya@apex.com", "company_id": comp_id},
            headers=headers,
        )
        contact_id = c_resp.json()["id"]

        camp_resp = await client.post(
            "/api/v1/campaigns",
            json={"name": "Completed Flow", "type": "sales_outbound"},
            headers=headers,
        )
        camp_id = camp_resp.json()["id"]

        steps_resp = await client.get(f"/api/v1/campaigns/{camp_id}/steps", headers=headers)
        step_id = steps_resp.json()[0]["id"]
        await client.patch(
            f"/api/v1/campaigns/{camp_id}/steps/{step_id}",
            json={
                "subject_template": "Strategic briefing for {contact.company}",
                "body_template": "Hi {contact.first_name}, Agile Sales & Marketing automates outbound.",
            },
            headers=headers,
        )
        await client.post(f"/api/v1/campaigns/{camp_id}/activate", headers=headers)

        # Enroll contact
        await client.post(
            f"/api/v1/campaigns/{camp_id}/contacts/{contact_id}",
            json={"enrollment_status": "queued"},
            headers=headers,
        )

        # Execute planning -> draft outreach created
        exec_resp = await client.post(f"/api/v1/campaigns/{camp_id}/execute", headers=headers)
        outreach_id = exec_resp.json()["created_outreach_ids"][0]

