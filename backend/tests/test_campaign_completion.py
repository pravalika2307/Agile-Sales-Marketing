async def register_tenant(client: AsyncClient, email: str, org_name: str) -> str:
    resp = await client.post(
        "/api/v1/auth/register",
        json={
            "email": email,
            "password": "Password123!",
            "full_name": "Completion Admin",
            "organization_name": org_name,
        },
    )
    assert resp.status_code == 201, f"Registration failed: {resp.text}"
    return resp.json()["tokens"]["access_token"]


@pytest.mark.asyncio
async def test_campaign_cannot_complete_solely_because_planning_finished(test_db_session):
    """
    Requirement 1 & 5: A campaign with draft outreach generated by planning
    CANNOT transition to Completed merely because planning finished.
    """
    async with make_client() as client:
        token = await register_tenant(client, "planning_test@test.com", "Planning Org")
        headers = {"Authorization": f"Bearer {token}"}

        # 1. Create contact
        c_resp = await client.post(
            "/api/v1/contacts",
            json={"first_name": "Kunal", "last_name": "Sadhre", "email": "kunal@example.com"},
            headers=headers,
        )
        contact_id = c_resp.json()["id"]

        # 2. Create and activate campaign
        camp_resp = await client.post(
            "/api/v1/campaigns",
            json={"name": "Outreach Sequence", "type": "sales_outbound"},
            headers=headers,
        )
        camp_id = camp_resp.json()["id"]

        steps_resp = await client.get(f"/api/v1/campaigns/{camp_id}/steps", headers=headers)
        step_id = steps_resp.json()[0]["id"]
        await client.patch(
            f"/api/v1/campaigns/{camp_id}/steps/{step_id}",
            json={
                "subject_template": "Briefing for {contact.company}",
                "body_template": "Hi {contact.first_name}, connecting from Agile Sales & Marketing.",
            },
            headers=headers,
        )

        await client.post(f"/api/v1/campaigns/{camp_id}/activate", headers=headers)

        # 3. Enroll contact
        await client.post(
            f"/api/v1/campaigns/{camp_id}/contacts/{contact_id}",
            json={"enrollment_status": "queued"},
            headers=headers,
        )

        # 4. Execute planning (generates draft outreach, sets contact to in_progress)
        exec_resp = await client.post(f"/api/v1/campaigns/{camp_id}/execute", headers=headers)
        assert exec_resp.status_code == 200
        assert exec_resp.json()["created_count"] == 1

        # 5. Attempting to complete campaign MUST be blocked with HTTP 400
        comp_resp = await client.post(f"/api/v1/campaigns/{camp_id}/complete", headers=headers)
        assert comp_resp.status_code == 400
        detail = comp_resp.json()["detail"].lower()
        assert "in-progress" in detail or "draft" in detail

        # Verify campaign remains active
        camp_check = await client.get(f"/api/v1/campaigns/{camp_id}", headers=headers)
        assert camp_check.json()["status"] == "active"


